-- catálogo de alimentos, recetas y menú semanal a mano. Una sola transacción.
-- Rutas Edge aditivas (D-008); nada toca 0001–0043. Sin permisos nuevos: lectura `menu.view`,
-- escritura `menu.plan.manage` (28 permisos / 47 defaults, como tras 0043).
--
-- Contenido:
-- * food: catálogo común (home_id nulo, solo lo escribe el seed con rol de servicio) o del hogar.
--   `name_norm` lo rellena un trigger con fn_meal_norm (minúsculas y sin acentos, sin la extensión
--   unaccent). El seed del catálogo común NO va en esta migración: supabase/seed/food_es.sql.
-- * recipe / recipe_ingredient: recetario del hogar; el ingrediente lleva `food_id` (catálogo) y siempre
--   una `label` (instantánea del nombre o texto libre).
-- * meal_plan (draft | accepted | archived, `revision` que sube en cada escritura; único por hogar y
--   semana no archivada), meal_plan_item (kind recipe | free_text | leftovers | eat_out; `title` es una
--   instantánea del nombre) y meal_plan_item_member (comensales).
-- * RLS: solo SELECT para authenticated; sin policies de escritura. Toda escritura pasa por RPC
--   security definer con fn_has_permission + audit_log `meal.*` (patrón 0043).
-- * Los ids son bigint identity como en el resto del esquema (no uuid).
--
