-- 0044_menus_semana.sql — change menus-semana (fase 2 de 5 del planificador de comidas):
-- catálogo de alimentos, recetas y menú semanal a mano. Una sola transacción.
-- Rutas Edge aditivas (D-008); nada toca 0001–0043. Sin permisos nuevos: lectura `menu.view`,
-- escritura `menu.plan.manage` (28 permisos / 47 defaults, como tras 0043).
--
-- Contenido:
-- * food: catálogo común (home_id nulo, solo lo escribe el seed con rol de servicio) o del hogar.
--   `name_norm` lo rellena un trigger con fn_meal_norm (minúsculas y sin acentos, sin la extensión
--   unaccent). El seed del catálogo común NO va en esta migración: supabase/seed/food_es.sql.
-- * recipe / recipe_ingredient: recetario del hogar; el ingrediente lleva `food_id` (catálogo) y siempre
--   una `label` (instantánea del nombre o texto libre).
-- * meal_plan (draft | accepted | archived, `revision` que sube en cada escritura; único por hogar y
--   semana no archivada), meal_plan_item (kind recipe | free_text | leftovers | eat_out; `title` es una
--   instantánea del nombre) y meal_plan_item_member (comensales).
-- * RLS: solo SELECT para authenticated; sin policies de escritura. Toda escritura pasa por RPC
--   security definer con fn_has_permission + audit_log `meal.*` (patrón 0043).
-- * Los ids son bigint identity como en el resto del esquema (no uuid).
--
-- Rollback: scripts/supabase/rollback/rollback_0044_menus_semana.sql (borra las tablas y sus datos).

begin;

-- ─────────────────── (a) Helpers ───────────────────

-- Minúsculas sin acentos para buscar y para la unicidad del catálogo. Inmutable y sin unaccent.
create or replace function fn_meal_norm(t text) returns text
language sql immutable as $$
    select lower(btrim(translate(t,
        'áàäâãéèëêíìïîóòöôõúùüûñçÁÀÄÂÃÉÈËÊÍÌÏÎÓÒÖÔÕÚÙÜÛÑÇ',
        'aaaaaeeeeiiiiooooouuuuncAAAAAEEEEIIIIOOOOOUUUUNC')))
$$;

-- Lista cerrada de los 14 alérgenos de la UE (sin 'other': el alimento es un dato objetivo).
create or replace function fn_meal_food_allergens_valid(a text[]) returns boolean
language sql immutable as $$
    select a is not null
       and a <@ array['gluten', 'crustaceans', 'egg', 'fish', 'peanut', 'soy', 'milk', 'tree_nuts', 'celery',
                      'mustard', 'sesame', 'sulphites', 'lupin', 'molluscs']::text[]
$$;

create or replace function fn_meal_food_before() returns trigger
language plpgsql as $$
begin
    new.name_norm := fn_meal_norm(new.name);
    return new;
end $$;

-- ─────────────────── (b) Tablas ───────────────────

create table food (
    id bigint generated by default as identity primary key,
    home_id bigint references home (id) on delete cascade,          -- nulo = catálogo común
    name text not null check (btrim(name) <> '' and char_length(name) <= 100),
    name_norm text not null,
    section text not null default 'otros' check (section in (
        'verdura', 'fruta', 'carne', 'embutido', 'pescado', 'marisco', 'lacteos', 'huevos', 'legumbres',
        'cereales', 'panaderia', 'despensa', 'aceites', 'especias', 'bebidas', 'congelados', 'otros')),
    allergens text[] not null default array[]::text[] check (fn_meal_food_allergens_valid(allergens)),
    default_unit text not null default 'g' check (default_unit in ('g', 'kg', 'ml', 'l', 'ud', 'cda', 'cdta', 'pizca', 'al gusto')),
    grams_per_unit numeric(10, 2) check (grams_per_unit > 0),
    created_at timestamp without time zone not null default (now() at time zone 'UTC')
);
create trigger food_before before insert or update on food
    for each row execute function fn_meal_food_before();
create unique index food_common_name_uq on food (name_norm) where home_id is null;
create unique index food_home_name_uq on food (home_id, name_norm) where home_id is not null;
create index food_name_norm_idx on food (name_norm text_pattern_ops);

create table recipe (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id) on delete cascade,
    name text not null check (btrim(name) <> '' and char_length(name) <= 120),
    servings integer not null default 2 check (servings between 1 and 100),
    minutes integer check (minutes between 0 and 1440),
    slots text[] not null default array[]::text[]                    -- franjas sugeridas (filtro)
        check (slots <@ array['breakfast', 'midmorning', 'lunch', 'snack', 'dinner']::text[]),
    steps text[] check (cardinality(steps) <= 50),
    created_by bigint references app_user (id) on delete set null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    unique (id, home_id)
);
create index recipe_home_idx on recipe (home_id);

create table recipe_ingredient (
    id bigint generated by default as identity primary key,
    recipe_id bigint not null references recipe (id) on delete cascade,
    home_id bigint not null references home (id) on delete cascade,
    position integer not null default 0,
    food_id bigint references food (id) on delete set null,
    label text not null check (btrim(label) <> '' and char_length(label) <= 120),
    quantity numeric(10, 2) check (quantity >= 0),
    unit text not null default 'ud' check (unit in ('g', 'kg', 'ml', 'l', 'ud', 'cda', 'cdta', 'pizca', 'al gusto'))
);
create index recipe_ingredient_recipe_idx on recipe_ingredient (recipe_id, position);
create index recipe_ingredient_home_idx on recipe_ingredient (home_id);

create table meal_plan (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id) on delete cascade,
    week_start date not null,
    status text not null default 'draft' check (status in ('draft', 'accepted', 'archived')),
    revision integer not null default 1 check (revision >= 0),
    accepted_at timestamp without time zone,
    accepted_by bigint references app_user (id) on delete set null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    unique (id, home_id)
);
create unique index meal_plan_home_week_uq on meal_plan (home_id, week_start) where status <> 'archived';

create table meal_plan_item (
    id bigint generated by default as identity primary key,
    plan_id bigint not null,
    home_id bigint not null,
    day date not null,
    slot text not null check (slot in ('breakfast', 'midmorning', 'lunch', 'snack', 'dinner')),
    position integer not null default 0 check (position >= 0),
    kind text not null check (kind in ('recipe', 'free_text', 'leftovers', 'eat_out')),
    recipe_id bigint,
    title text not null default '' check (char_length(title) <= 200),   -- instantánea del nombre
    servings integer check (servings between 1 and 100),
    cook_member_id bigint,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    unique (id, home_id),
    constraint meal_plan_item_pos_uq unique (plan_id, day, slot, position) deferrable initially deferred,
    constraint meal_plan_item_plan_fk foreign key (plan_id, home_id)
        references meal_plan (id, home_id) on delete cascade,
    constraint meal_plan_item_recipe_fk foreign key (recipe_id, home_id)
        references recipe (id, home_id) on delete set null (recipe_id),
    constraint meal_plan_item_cook_fk foreign key (cook_member_id, home_id)
        references home_member (id, home_id) on delete set null (cook_member_id)
);
create index meal_plan_item_home_idx on meal_plan_item (home_id);
create index meal_plan_item_recipe_idx on meal_plan_item (recipe_id);

create table meal_plan_item_member (
    item_id bigint not null,
    home_id bigint not null,
    member_id bigint not null,
    primary key (item_id, member_id),
    constraint meal_plan_item_member_item_fk foreign key (item_id, home_id)
        references meal_plan_item (id, home_id) on delete cascade,
    constraint meal_plan_item_member_member_fk foreign key (member_id, home_id)
        references home_member (id, home_id) on delete cascade
);
create index meal_plan_item_member_home_idx on meal_plan_item_member (home_id);

-- ─────────────────── (c) RLS: solo lectura ───────────────────

alter table food enable row level security;
alter table recipe enable row level security;
alter table recipe_ingredient enable row level security;
alter table meal_plan enable row level security;
alter table meal_plan_item enable row level security;
alter table meal_plan_item_member enable row level security;
revoke all on food, recipe, recipe_ingredient, meal_plan, meal_plan_item, meal_plan_item_member
    from public, anon, authenticated;
grant select on food, recipe, recipe_ingredient, meal_plan, meal_plan_item, meal_plan_item_member
    to authenticated;

-- el catálogo común lo lee cualquier usuario autenticado; el del hogar, quien tenga menu.view
create policy food_select on food for select to authenticated
    using (home_id is null
           or (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view')));
create policy recipe_select on recipe for select to authenticated
    using (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view'));
create policy recipe_ingredient_select on recipe_ingredient for select to authenticated
    using (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view'));
create policy meal_plan_select on meal_plan for select to authenticated
    using (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view'));
create policy meal_plan_item_select on meal_plan_item for select to authenticated
    using (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view'));
create policy meal_plan_item_member_select on meal_plan_item_member for select to authenticated
    using (home_id = any (fn_my_home_ids()) and fn_has_permission(home_id, 'menu.view'));

revoke all on function fn_meal_norm(text), fn_meal_food_allergens_valid(text[]), fn_meal_food_before()
    from public, anon, authenticated;

commit;
