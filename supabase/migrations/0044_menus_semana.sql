    allergens text[] not null default array[]::text[] check (fn_meal_food_allergens_valid(allergens)),
    default_unit text not null default 'g' check (default_unit in ('g', 'kg', 'ml', 'l', 'ud', 'cda', 'cdta', 'pizca', 'al gusto')),
