    if not found then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    if p_expected_revision is not null and p_expected_revision <> v_plan.revision then
        raise exception 'Stale meal plan revision' using errcode = 'P0001';
    end if;
