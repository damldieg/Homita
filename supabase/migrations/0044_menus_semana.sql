-- ─────────────────── (e) RPC del plan semanal ───────────────────
-- Errores: 'Invalid meal plan' (P0001), 'Stale meal plan revision' (P0001, revisión vieja; la Edge lo
-- mapea a 409), 'Meal plan exists' (P0001, semana ocupada; 409), 'Not Found' (P0002), 'Not Allowed' (42501).
-- Ciclo: upsert crea el plan en draft (con p_expected_revision = 0) y cada llamada sube `revision` una vez.
-- Editar un plan accepted lo devuelve a draft. accept exige draft y al menos una casilla. archive libera
-- la semana. Toda escritura devuelve el plan completo (con la revisión nueva).

-- Primer día de la semana (según meal_profile.week_start_day, 1 = lunes) que contiene p_day.
create or replace function fn_meal_week_of(p_home bigint, p_day date) returns date
language sql stable security definer set search_path = public as $$
    select p_day - (((extract(isodow from p_day)::integer
                      - coalesce((select p.week_start_day from meal_profile p where p.home_id = p_home), 1)) + 7) % 7)
$$;

create or replace function fn_meal_plan_json(p_id bigint) returns json
language sql stable security definer set search_path = public as $$
    select json_build_object(
        'id', p.id, 'week_start', p.week_start, 'status', p.status, 'revision', p.revision,
        'accepted_at', p.accepted_at, 'accepted_by', p.accepted_by, 'updated_at', p.updated_at,
        'items', (select coalesce(json_agg(json_build_object(
                'id', i.id, 'day', i.day, 'slot', i.slot, 'position', i.position, 'kind', i.kind,
                'recipe_id', i.recipe_id, 'title', i.title, 'servings', i.servings,
                'cook_member_id', i.cook_member_id,
                'members', (select coalesce(json_agg(m.member_id order by m.member_id), '[]'::json)
                            from meal_plan_item_member m where m.item_id = i.id))
                order by i.day, array_position(array['breakfast', 'midmorning', 'lunch', 'snack', 'dinner'], i.slot),
                         i.position, i.id), '[]'::json)
            from meal_plan_item i where i.plan_id = p.id))
    from meal_plan p where p.id = p_id
$$;

