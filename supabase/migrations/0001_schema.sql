-- 0001_schema.sql — Esquema Postgres de Homita (compat. Planify-Backend, modelo histórico) (fase 1, D-002).
-- Ingeniería inversa del modelo PHP real (histórico: backend retirado, D-008 y tag legacy-php-final).
--
-- Notas:
-- * `user` se renombra app_user (`user` es palabra reservada en PG). No viajan `password`/`token`:
--   Supabase Auth los sustituye (auth.users ↔ app_user.auth_uid).
-- * `date_at` y afines son hora local flotante (Madrid): timestamp without time zone, sin conversión
--   de zona al migrar. Los writes fijan (now() at time zone 'UTC') para igualar el formato SQLite
--   'YYYY-MM-DD HH:MM:SS' byte a byte (R1-07).
-- * 10 tablas conservan `id bigint IDENTITY` con los ids originales; las 5 de PK compuesta
--   (routine_user, routine_exception, routine_event_alarm, event_person, routine_person) NO llevan
--   id, igual que en SQLite (R1-06).
-- * `task."order"` y `routine."interval"` van comillados (palabras reservadas).
-- * Flags SQLite 0/1 (widget, dashboard, active, cancelled) → boolean.

create type user_role as enum ('owner', 'viewer');
create type task_list_sort as enum ('updated_at', 'title', 'custom');
create type routine_frequency as enum ('daily', 'weekly', 'monthly');

create table app_user (
    id bigint generated by default as identity primary key,
    auth_uid uuid unique references auth.users (id) on delete cascade,
    name text not null,
    email text not null unique,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table calendar (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null default '#6923E2',
    token text not null unique,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table routine (
    id bigint generated by default as identity primary key,
    calendar_id bigint not null references calendar (id) on delete cascade,
    title text not null,
    days jsonb not null,
    time text not null check (time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    start_date date not null,
    end_date date,
    active boolean not null default true,
    available_from timestamp without time zone not null,
    frequency routine_frequency not null default 'weekly',
    "interval" integer not null default 1 check ("interval" between 1 and 99),
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table event (
    id bigint generated by default as identity primary key,
    calendar_id bigint not null references calendar (id) on delete cascade,
    title text not null,
    date_at timestamp without time zone not null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    routine_id bigint references routine (id) on delete set null,
    routine_date date
);
create unique index event_routine_date on event (routine_id, routine_date);

create table event_user (
    id bigint generated by default as identity primary key,
    event_id bigint not null references event (id) on delete cascade,
    user_id bigint not null references app_user (id) on delete cascade,
    alarm integer,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    unique (event_id, user_id)
);

create table task_list (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null default '#6923E2',
    token text not null unique,
    sort task_list_sort not null default 'updated_at',
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table task_list_user (
    id bigint generated by default as identity primary key,
    task_list_id bigint not null references task_list (id) on delete cascade,
    user_id bigint not null references app_user (id) on delete cascade,
    role user_role not null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    widget boolean not null default true,
    dashboard boolean not null default true
);

create table task (
    id bigint generated by default as identity primary key,
    task_list_id bigint not null references task_list (id) on delete cascade,
    title text not null,
    completed_at timestamp without time zone,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    "order" integer not null default 0
);

create table calendar_user (
    id bigint generated by default as identity primary key,
    calendar_id bigint not null references calendar (id) on delete cascade,
    user_id bigint not null references app_user (id) on delete cascade,
    role user_role not null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    widget boolean not null default true,
    dashboard boolean not null default true
);

create table routine_user (
    routine_id bigint not null references routine (id) on delete cascade,
    user_id bigint not null references app_user (id) on delete cascade,
    alarm integer,
    primary key (routine_id, user_id)
);

create table routine_exception (
    routine_id bigint not null references routine (id) on delete cascade,
    routine_date date not null,
    title text,
    date_at timestamp without time zone,
    cancelled boolean not null default false,
    primary key (routine_id, routine_date)
);

create table routine_event_alarm (
    routine_id bigint not null references routine (id) on delete cascade,
    routine_date date not null,
    user_id bigint not null references app_user (id) on delete cascade,
    alarm integer,
    primary key (routine_id, routine_date, user_id)
);

create table person (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    name text not null,
    color text not null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table event_person (
    event_id bigint not null references event (id) on delete cascade,
    person_id bigint not null references person (id) on delete cascade,
    primary key (event_id, person_id)
);

create table routine_person (
    routine_id bigint not null references routine (id) on delete cascade,
    person_id bigint not null references person (id) on delete cascade,
    primary key (routine_id, person_id)
);

create index person_user on person (user_id);
create index event_person_person on event_person (person_id);
create index routine_person_person on routine_person (person_id);
