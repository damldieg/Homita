-- 0049_home_display.sql — Pantalla del hogar (change dashboard-pantalla-hogar, paso 3 de la mejora).
--
-- Opción (a) del plan: cada pantalla es una cuenta técnica del hogar (app_user propio, sin contraseña
-- conocida) con un home_member de kind 'display' y permisos de solo lectura. Su selección de
-- calendarios y listas se refleja en calendar_user / task_list_user (dashboard = true, role viewer), así
-- que GET /event?dashboard=true y GET /task?dashboard=true siguen igual que para una persona.
--
-- Vinculación (sin sesión en la pantalla):
--   1. link_start (service_role, Edge): código de 6 dígitos (un uso, 10 min) + secreto de sondeo (solo hash).
--   2. link_claim (admin con display.manage, JWT del usuario): marca el código como usado y guarda hogar y nombre.
--   3. La Edge crea la cuenta técnica en GoTrue (contraseña aleatoria, nunca guardada) e inicia sesión.
--   4. link_complete (service_role): crea home_display + membresía + home_member y deja la sesión pendiente.
--   5. link_poll (service_role, sondeo de la pantalla): entrega la sesión una sola vez.
--
-- Decisiones (plan.md y brief.md): límite de 5 pantallas activas por hogar; display.manage lo tienen los
-- que gestionan calendarios (calendar.manage) además de los admins, comprobado en fn_can_manage_displays.
--
-- Las tablas no tienen policies de RLS: solo se accede por RPC SECURITY DEFINER (como task_person).
-- Rollback: scripts/supabase/rollback/rollback_0049_home_display.sql (el valor 'display' del enum no se
-- puede quitar en PostgreSQL y queda; no hay filas que lo usen tras el rollback).

-- ─────────────── A. Kind y permiso nuevos ───────────────
alter type member_kind add value if not exists 'display';

insert into permission (code, domain, description) values
    ('display.manage', 'display', 'Vincular, configurar y revocar pantallas del hogar')
on conflict (code) do nothing;

-- Backfill (solo códigos que faltan): quien ya tiene calendar.manage gestiona pantallas.
insert into membership_permission (home_membership_id, permission_code)
select mp.home_membership_id, 'display.manage'
from membership_permission mp
where mp.permission_code = 'calendar.manage'
on conflict do nothing;

-- ─────────────── B. Tablas ───────────────
create table home_display (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id),
    app_user_id bigint not null references app_user (id) on delete cascade,
    home_member_id bigint,
    name text not null check (btrim(name) <> '' and char_length(name) <= 50),
    settings jsonb not null default '{}'::jsonb check (jsonb_typeof(settings) = 'object'),
    linked_by bigint references app_user (id) on delete set null,
    last_seen_at timestamp without time zone,
    revoked_at timestamp without time zone,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);
create unique index home_display_app_user_key on home_display (app_user_id);
create index home_display_home_active_idx on home_display (home_id) where revoked_at is null;

create table home_display_calendar (
    display_id bigint not null references home_display (id) on delete cascade,
    calendar_id bigint not null references calendar (id) on delete cascade,
    primary key (display_id, calendar_id)
);

create table home_display_task_list (
    display_id bigint not null references home_display (id) on delete cascade,
    task_list_id bigint not null references task_list (id) on delete cascade,
    primary key (display_id, task_list_id)
);

-- Vinculación pendiente. El código y el secreto de sondeo se guardan como hash (sha256).
create table home_display_link (
    id bigint generated by default as identity primary key,
    code_hash text not null,
    poll_hash text not null,
    expires_at timestamp without time zone not null,
    home_id bigint references home (id),
    display_name text,
    claimed_by bigint references app_user (id) on delete set null,
    claimed_at timestamp without time zone,
    display_id bigint references home_display (id) on delete cascade,
    session jsonb,
    delivered_at timestamp without time zone,
    created_at timestamp without time zone not null default (now() at time zone 'UTC')
);
create unique index home_display_link_code_key on home_display_link (code_hash) where claimed_at is null;
create unique index home_display_link_poll_key on home_display_link (poll_hash);

-- Intentos de código fallidos por usuario (el código no identifica una vinculación si es incorrecto).
create table home_display_attempt (
    id bigint generated by default as identity primary key,
    app_user_id bigint not null references app_user (id) on delete cascade,
    failed_at timestamp without time zone not null default (now() at time zone 'UTC')
);
create index home_display_attempt_user_idx on home_display_attempt (app_user_id, failed_at);

alter table home_display enable row level security;
alter table home_display_calendar enable row level security;
alter table home_display_task_list enable row level security;
alter table home_display_link enable row level security;
alter table home_display_attempt enable row level security;

-- ─────────────── C. Helpers ───────────────
-- display.manage, o calendar.manage (los que gestionan calendarios también gestionan pantallas; decisión 3).
create or replace function fn_can_manage_displays(p_home_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select fn_has_permission(p_home_id, 'display.manage') or fn_has_permission(p_home_id, 'calendar.manage')
$$;

-- Hash del código o del secreto: sha256 en hex (pgcrypto de extensions, como 0022/0026).
create or replace function fn_display_hash(p_value text) returns text
language sql immutable set search_path = public, extensions as $$
    select encode(extensions.digest(p_value, 'sha256'), 'hex')
$$;

-- ─────────────── D. RPC: vinculación ───────────────

-- link_start: solo la Edge (service_role). Devuelve el código y el secreto de sondeo en claro (una vez).
create or replace function fn_display_link_start() returns json
language plpgsql security definer set search_path = public, extensions as $$
declare
    v_code text;
    v_poll text;
    v_expires timestamp := (now() at time zone 'UTC') + interval '10 minutes';
    v_tries int := 0;
begin
    -- Las pendientes caducadas se guardan una hora más para que el sondeo diga «expired»
    delete from home_display_link where claimed_at is null and expires_at < (now() at time zone 'UTC') - interval '1 hour';
    if (select count(*) from home_display_link where claimed_at is null) >= 50 then
        raise exception 'Too many pending links';
    end if;
    loop
        v_tries := v_tries + 1;
        v_code := lpad((floor(random() * 1000000))::int::text, 6, '0');
        exit when not exists (select 1 from home_display_link
                              where code_hash = fn_display_hash(v_code) and claimed_at is null);
        if v_tries > 50 then raise exception 'Too many pending links'; end if;
    end loop;
    v_poll := encode(extensions.gen_random_bytes(24), 'hex');
    insert into home_display_link (code_hash, poll_hash, expires_at)
    values (fn_display_hash(v_code), fn_display_hash(v_poll), v_expires);
    return json_build_object('code', v_code, 'poll_secret', v_poll, 'expires_at',
        to_char(v_expires, 'YYYY-MM-DD HH24:MI:SS'));
end
$$;

-- link_claim: un admin (o quien gestiona calendarios) con el hogar en la cabecera. Un solo uso, 5 fallos
-- por usuario en 10 min y 5 pantallas activas por hogar. Los errores de código devuelven {error} (la Edge los
-- traduce); el resto de errores se lanzan.
create or replace function fn_display_link_claim(p_home_id bigint, p_code text, p_name text) returns json
language plpgsql security definer set search_path = public, extensions as $$
declare
    v_me bigint := fn_my_user_id();
    v_link home_display_link;
    v_name text := btrim(coalesce(p_name, ''));
begin
    if not fn_can_manage_displays(p_home_id) then raise exception 'Not Allowed'; end if;
    if v_name = '' or char_length(v_name) > 50 then raise exception 'Name is required (max 50 characters)'; end if;
    if (select count(*) from home_display_attempt
        where app_user_id = v_me and failed_at > (now() at time zone 'UTC') - interval '10 minutes') >= 5 then
        return json_build_object('error', 'Too many attempts');
    end if;
    select * into v_link from home_display_link
    where code_hash = fn_display_hash(coalesce(p_code, ''))
      and claimed_at is null and expires_at > (now() at time zone 'UTC')
    for update;
    if not found then
        -- Se devuelve (no se lanza) para que el intento fallido quede guardado: un raise deshace el insert.
        insert into home_display_attempt (app_user_id) values (v_me);
        return json_build_object('error', 'Invalid link code');
    end if;
    if (select count(*) from home_display where home_id = p_home_id and revoked_at is null) >= 5 then
        raise exception 'Display limit reached';
    end if;
    update home_display_link
    set home_id = p_home_id, display_name = v_name, claimed_by = v_me,
        claimed_at = (now() at time zone 'UTC')
    where id = v_link.id;
    return json_build_object('link_id', v_link.id, 'home_id', p_home_id, 'name', v_name);
end
$$;

-- link_complete: solo la Edge, tras crear la cuenta técnica en GoTrue. Deja la sesión pendiente de entrega.
create or replace function fn_display_link_complete(p_link_id bigint, p_auth_uid uuid, p_session jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_link home_display_link;
    v_app_user bigint;
    v_membership bigint;
    v_member bigint;
    v_display bigint;
begin
    select * into v_link from home_display_link where id = p_link_id for update;
    if not found or v_link.claimed_at is null or v_link.display_id is not null then
        raise exception 'Not Found';
    end if;
    select id into v_app_user from app_user where auth_uid = p_auth_uid;
    if v_app_user is null then raise exception 'Not Found'; end if;

    insert into home_membership (home_id, app_user_id, role)
    values (v_link.home_id, v_app_user, 'member')
    returning id into v_membership;
    insert into home_member (home_id, kind, name, app_user_id)
    values (v_link.home_id, 'display', v_link.display_name, v_app_user)
    returning id into v_member;
    -- Solo lectura: ver calendarios, tareas y menú, y nada de escritura.
    insert into membership_permission (home_membership_id, permission_code)
    values (v_membership, 'calendar.view'), (v_membership, 'task.view'), (v_membership, 'menu.view');

    insert into home_display (home_id, app_user_id, home_member_id, name, linked_by)
    values (v_link.home_id, v_app_user, v_member, v_link.display_name, v_link.claimed_by)
    returning id into v_display;
    -- Hogar por defecto de la cuenta: las lecturas de la pantalla (menú de hoy) sin cabecera lo usan
    update app_user set default_home_id = v_link.home_id where id = v_app_user and default_home_id is null;

    update home_display_link set display_id = v_display, session = p_session where id = p_link_id;
    return json_build_object('display_id', v_display);
end
$$;

-- link_poll: solo la Edge (sondeo de la pantalla con su secreto). Entrega la sesión una sola vez.
create or replace function fn_display_link_poll(p_poll_secret text) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_link home_display_link;
    v_display home_display;
    v_session jsonb;
begin
    select * into v_link from home_display_link where poll_hash = fn_display_hash(coalesce(p_poll_secret, ''));
    if not found then raise exception 'Not Found'; end if;
    if v_link.session is not null then
        v_session := v_link.session;
        update home_display_link set session = null, delivered_at = (now() at time zone 'UTC') where id = v_link.id;
        select * into v_display from home_display where id = v_link.display_id;
        return json_build_object('status', 'ready', 'session', v_session,
            'display', json_build_object('id', v_display.id, 'home_id', v_display.home_id, 'name', v_display.name));
    end if;
    if v_link.delivered_at is not null then raise exception 'Not Found'; end if;
    if v_link.claimed_at is null and v_link.expires_at <= (now() at time zone 'UTC') then
        return json_build_object('status', 'expired');
    end if;
    return json_build_object('status', 'pending');
end
$$;

-- link_abort: la Edge deshace una vinculación a medias (fallo al crear la cuenta técnica).
create or replace function fn_display_link_abort(p_link_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_display bigint;
begin
    select display_id into v_display from home_display_link where id = p_link_id;
    if v_display is not null then
        delete from home_display where id = v_display;
    end if;
    delete from home_display_link where id = p_link_id;
end
$$;

-- ─────────────── E. RPC: gestión desde el móvil ───────────────

-- Lista de pantallas del hogar (cualquier miembro ve cuáles hay).
create or replace function fn_display_list(p_home_id bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
    perform fn_require_member(p_home_id);
    return coalesce((
        select json_agg(json_build_object(
            'id', d.id, 'name', d.name, 'settings', d.settings,
            'last_seen_at', to_char(d.last_seen_at, 'YYYY-MM-DD HH24:MI:SS'),
            'calendar_ids', coalesce((select json_agg(c.calendar_id order by c.calendar_id)
                                      from home_display_calendar c where c.display_id = d.id), '[]'::json),
            'task_list_ids', coalesce((select json_agg(t.task_list_id order by t.task_list_id)
                                       from home_display_task_list t where t.display_id = d.id), '[]'::json)
        ) order by d.id)
        from home_display d where d.home_id = p_home_id and d.revoked_at is null
    ), '[]'::json);
end
$$;

-- Actualiza nombre, ajustes y selección. La selección se refleja en calendar_user / task_list_user.
create or replace function fn_display_update(p_home_id bigint, p_display_id bigint, p_name text,
    p_settings jsonb, p_calendar_ids bigint[], p_task_list_ids bigint[]) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_display home_display;
    v_name text := btrim(coalesce(p_name, ''));
    v_cal bigint[] := coalesce(p_calendar_ids, '{}');
    v_tl bigint[] := coalesce(p_task_list_ids, '{}');
begin
    if not fn_can_manage_displays(p_home_id) then raise exception 'Not Allowed'; end if;
    select * into v_display from home_display where id = p_display_id and home_id = p_home_id and revoked_at is null for update;
    if not found then raise exception 'Not Found'; end if;
    if v_name = '' or char_length(v_name) > 50 then raise exception 'Name is required (max 50 characters)'; end if;
    if p_settings is not null and jsonb_typeof(p_settings) <> 'object' then raise exception 'Invalid display settings'; end if;
    -- Solo calendarios y listas del propio hogar
    if exists (select 1 from unnest(v_cal) c where not exists (select 1 from calendar where id = c and home_id = p_home_id))
       or exists (select 1 from unnest(v_tl) t where not exists (select 1 from task_list where id = t and home_id = p_home_id)) then
        raise exception 'Invalid display selection';
    end if;

    update home_display
    set name = v_name, settings = coalesce(p_settings, settings), updated_at = (now() at time zone 'UTC')
    where id = p_display_id;

    -- Calendarios: quitar los que sobran y añadir los nuevos (viewer, con dashboard)
    delete from calendar_user cu
    where cu.user_id = v_display.app_user_id and cu.calendar_id not in (select unnest(v_cal));
    insert into calendar_user (calendar_id, user_id, role, widget, dashboard, home_id)
    select c, v_display.app_user_id, 'viewer', false, true, p_home_id from unnest(v_cal) c
    on conflict do nothing;
    update calendar_user set dashboard = true where user_id = v_display.app_user_id and calendar_id in (select unnest(v_cal));
    delete from home_display_calendar where display_id = p_display_id;
    insert into home_display_calendar (display_id, calendar_id) select p_display_id, c from unnest(v_cal) c;

    -- Listas: igual
    delete from task_list_user tu
    where tu.user_id = v_display.app_user_id and tu.task_list_id not in (select unnest(v_tl));
    insert into task_list_user (task_list_id, user_id, role, widget, dashboard, home_id)
    select t, v_display.app_user_id, 'viewer', false, true, p_home_id from unnest(v_tl) t
    on conflict do nothing;
    update task_list_user set dashboard = true where user_id = v_display.app_user_id and task_list_id in (select unnest(v_tl));
    delete from home_display_task_list where display_id = p_display_id;
    insert into home_display_task_list (display_id, task_list_id) select p_display_id, t from unnest(v_tl) t;

    return json_build_object('id', p_display_id);
end
$$;

-- Revoca: quita membresía, selección y permisos. Devuelve el auth_uid para que la Edge borre la cuenta de GoTrue.
create or replace function fn_display_revoke(p_home_id bigint, p_display_id bigint) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_display home_display;
    v_auth uuid;
begin
    if not fn_can_manage_displays(p_home_id) then raise exception 'Not Allowed'; end if;
    select * into v_display from home_display where id = p_display_id and home_id = p_home_id and revoked_at is null for update;
    if not found then raise exception 'Not Found'; end if;
    select auth_uid into v_auth from app_user where id = v_display.app_user_id;

    delete from calendar_user where user_id = v_display.app_user_id;
    delete from task_list_user where user_id = v_display.app_user_id;
    delete from home_member where id = v_display.home_member_id;
    delete from home_membership where home_id = p_home_id and app_user_id = v_display.app_user_id;
    update app_user set default_home_id = null where id = v_display.app_user_id and default_home_id = p_home_id;
    update home_display set revoked_at = (now() at time zone 'UTC'), updated_at = (now() at time zone 'UTC')
    where id = p_display_id;

    return json_build_object('id', p_display_id, 'auth_uid', v_auth);
end
$$;

-- Configuración que la pantalla lee de sí misma (con su propia sesión). Marca cuándo se vio por última vez.
create or replace function fn_display_config() returns json
language plpgsql security definer set search_path = public as $$
declare v_display home_display;
begin
    select * into v_display from home_display where app_user_id = fn_my_user_id() and revoked_at is null;
    if not found then raise exception 'Not Found'; end if;
    update home_display set last_seen_at = (now() at time zone 'UTC') where id = v_display.id;
    return json_build_object(
        'id', v_display.id, 'home_id', v_display.home_id, 'name', v_display.name, 'settings', v_display.settings,
        'calendar_ids', coalesce((select json_agg(c.calendar_id order by c.calendar_id)
                                  from home_display_calendar c where c.display_id = v_display.id), '[]'::json),
        'task_list_ids', coalesce((select json_agg(t.task_list_id order by t.task_list_id)
                                   from home_display_task_list t where t.display_id = v_display.id), '[]'::json));
end
$$;

