-- 0032_feedback_schema.sql — change control-ios-feedback: DDL de `public.backlog` y `public.feedback`
-- para local/CI, alineado con la definición de prod (volcado de solo lectura 2026-11-19 ~14:00).
-- Todo con `if not exists` / guardas idempotentes: en prod, donde las tablas ya existen, es no-op.
--
-- ORDEN CON 0031 (importante): 0031 crea el trigger `homita_feedback_creation` SOLO si
-- `public.feedback` ya existe, y su URL es la de la función `procesar-feedback` de PROD. En un
-- `db reset` local 0031 corre antes que esta migración, ve la tabla inexistente y sale sin crear el
-- trigger. Por eso la tabla se crea aquí (después) y esta migración NO crea ningún trigger.
-- Si alguien reaplica 0031 a mano con la tabla ya creada en local, el trigger apuntaría a prod:
-- no hacerlo; usar siempre `db reset` (orden 0031 -> 0032).
--
-- Diferencias frente a la definición de prod (T3): ninguna de columnas/tipos/checks. Matices:
--   * `created_at` es timestamptz not null default now() (el volcado solo indica «created_at»).
--   * La política de INSERT lleva guarda idempotente (sin drop) para no alterar prod.
--   * Sin política de SELECT: el cliente no lee feedback; backlog sin políticas (solo service_role).

create table if not exists public.backlog (
    id bigint generated by default as identity primary key,
    titulo text not null,
    descripcion text,
    seccion text,
    subseccion text,
    tipo text check (tipo in ('bug', 'mejora')),
    votos integer default 1,
    created_at timestamptz not null default now()
);

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    user_id uuid default auth.uid() references auth.users (id),
    seccion text not null,
    subseccion text,
    tipo text not null check (tipo in ('bug', 'mejora')),
    texto text not null,
    estado text not null default 'pendiente',
    backlog_id bigint references public.backlog (id),
    created_at timestamptz not null default now()
);

alter table public.backlog enable row level security;
alter table public.feedback enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'feedback' and policyname = 'insertar mi feedback'
    ) then
        create policy "insertar mi feedback" on public.feedback
            for insert to authenticated
            with check (user_id = auth.uid());
    end if;
end $$;
