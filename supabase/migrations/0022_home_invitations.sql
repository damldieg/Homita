-- 0022_home_invitations.sql — Invitaciones y vinculación de cuentas (fase 1.15, tarjeta 1.15;
-- diseno-home.md §5.2). Una sola transacción, aditiva: NO modifica 0001–0021 ni redefine ninguna
-- función existente (add_calendar_user/add_task_list_user siguen con el 403 de 0021: Q2 a).
--
-- Contenido:
-- * Tabla home_invitation: código de 128 bits (CSPRNG, extensions.gen_random_bytes) del que solo
--   se guarda el sha256 hex (CHECK de formato); status pending/accepted/revoked ('expired' no se
--   guarda: se calcula con expires_at <= now UTC); caducidad de 7 días; un solo uso. FK compuesta
--   (member_id, home_id) → home_member (id, home_id): la BD impide apuntar a un miembro de otro
--   hogar. RLS activada SIN policies (D-014: acceso solo por RPC security definer, como
--   audit_log) y sin privilegios de tabla ni secuencia para anon/authenticated (los default
--   privileges de Supabase los concederían a los objetos nuevos).
-- * Helper fn_home_invitation_json (forma INVITATION_ITEM; nunca code ni code_hash), sin grants.
-- * RPC (security definer, search_path = public; primera sentencia fn_my_user_id() null → 'Not
--   Allowed' 42501): get_home_invitations, create_home_invitation, accept_home_invitation y
--   revoke_home_invitation. Convención D-a: 'Not Found' P0002 (→ 404 en /home/*), 'Not Allowed'
--   42501 (→ 403), 'Invalid member' y 'Already member' P0001 (→ 400 por RPC_STATUS).
-- * D-015: accept NO lee fn_active_home_id() (la cabecera X-Home-Id se ignora; la Edge tampoco
--   la propaga en esa ruta). El usuario aún no es miembro: no usa fn_home_mutation_guard; replica
--   solo el FOR UPDATE del hogar y el filtro de archived.
-- * D-017: solo un admin crea invitaciones de kind adult (con o sin member_id). Al aceptar, una
--   invitación no-adult cuyo miembro pasó a adult entre crear y aceptar → 'Invalid member' (sin
--   consumir), para que la regla no se pueda saltar cambiando el kind del miembro.
-- * Decisiones menores (plan 1.15): sha256 nativo de PG (A-3, igual byte a byte a
--   extensions.digest); con member_id el kind es el del miembro (kind distinto → Invalid member)
--   y al aceptar se usa su kind ACTUAL (A-2); el listado solo devuelve pendientes no caducadas y
--   revocar una caducada → Not Found (A-4); auditoría home.invitation.create|accept|revoke en
--   audit_log sin código ni hash (A-6); varias invitaciones al mismo miembro: la primera que se
--   acepta vincula y el resto → Invalid member (A-9).
--
-- Orden de locks (compatible con 0021:3-4 y 0018): hogar (FOR UPDATE) → home_member (FOR UPDATE)
-- → home_membership (insert; su FK toma KEY SHARE sobre app_user) → membership_permission (seed)
-- → home_invitation (FOR UPDATE + update) → audit_log. create: hogar → home_member → insert
-- home_invitation → audit_log; revoke: hogar → home_invitation → audit_log; get: sin locks.
-- Todos los escritores de home_invitation toman antes el lock de hogar: dos accept del mismo
-- código se serializan en home y el segundo relee (READ COMMITTED, snapshot nuevo) → Not Found.
-- La lectura previa sin lock de accept solo sirve para saber qué hogar bloquear.
--
-- Rollback: scripts/supabase/rollback/rollback_0022.sql (drop de las 5 funciones y la tabla; NO
-- revierte membresías, home_member, person, snapshots ni audit_log de las aceptaciones ni la
-- extensión pgcrypto).

begin;

-- En Supabase pgcrypto ya vive en el esquema extensions (no-op); el rollback no la toca.
create extension if not exists pgcrypto with schema extensions;

-- ─────────────────── (a) Tabla home_invitation ───────────────────

create table home_invitation (
    id          bigint generated by default as identity primary key,
    home_id     bigint not null references home (id) on delete cascade,
    kind        member_kind not null,
    member_id   bigint,
    code_hash   text not null,
    status      text not null default 'pending',
    expires_at  timestamp without time zone not null,
    created_by  bigint references app_user (id) on delete set null,
    accepted_by bigint references app_user (id) on delete set null,
    accepted_at timestamp without time zone,
    created_at  timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at  timestamp without time zone not null default (now() at time zone 'UTC'),
    constraint home_invitation_code_hash_key unique (code_hash),
    constraint home_invitation_status_check check (status in ('pending', 'accepted', 'revoked')),
    constraint home_invitation_code_hash_format check (code_hash ~ '^[0-9a-f]{64}$'),
    constraint home_invitation_no_pet check (kind <> 'pet'),
    constraint home_invitation_accepted_check check ((status = 'accepted') = (accepted_at is not null)),
    constraint home_invitation_member_fk foreign key (member_id, home_id)
        references home_member (id, home_id) on delete cascade
);
create index home_invitation_home_pending_idx on home_invitation (home_id, id) where status = 'pending';
create index home_invitation_member_idx on home_invitation (member_id) where member_id is not null;

alter table home_invitation enable row level security;
revoke all on home_invitation from public, anon, authenticated;
revoke all on sequence home_invitation_id_seq from public, anon, authenticated;

-- ─────────────────── (b) Helper de salida INVITATION_ITEM (sin grants) ───────────────────

create or replace function fn_home_invitation_json(p_id bigint) returns json
language sql stable security definer set search_path = public as $$
    select json_build_object(
        'id', i.id, 'home_id', i.home_id, 'kind', i.kind::text, 'member_id', i.member_id,
        'member_name', hm.name, 'status', i.status,
        'expires_at', to_char(i.expires_at, 'YYYY-MM-DD HH24:MI:SS'),
        'created_by', i.created_by,
        'created_at', to_char(i.created_at, 'YYYY-MM-DD HH24:MI:SS'))
    from home_invitation i left join home_member hm on hm.id = i.member_id
    where i.id = p_id
$$;
revoke all on function fn_home_invitation_json(bigint) from public, anon, authenticated;

-- ─────────────────── (c) RPC ───────────────────

-- GET /home/invitation?home_id=: pendientes no caducadas del hogar (id desc). Cabecera ≠ home_id
-- o no miembro → Not Found; sin home.invite → Not Allowed.
create or replace function get_home_invitations(p_home_id bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
    if fn_my_user_id() is null then
        raise exception 'Not Allowed' using errcode = '42501';
    end if;
    if fn_active_home_id() is not null and fn_active_home_id() <> p_home_id then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    perform fn_require_permission(p_home_id, 'home.invite');
    return (
        select coalesce(json_agg(fn_home_invitation_json(i.id) order by i.id desc), '[]'::json)
        from home_invitation i
        where i.home_id = p_home_id and i.status = 'pending'
          and i.expires_at > (now() at time zone 'UTC')
    );
end $$;

-- POST /home/invitation/create {home_id, kind?, member_id?} → INVITATION_ITEM + code (el código
-- en claro solo sale aquí, una vez). Validación de entrada sin locks → guard (hogar FOR UPDATE,
-- archived, cabecera, miembro) → home.invite → miembro objetivo FOR UPDATE → D-017 → insert.
create or replace function create_home_invitation(
    p_home_id bigint, p_kind text, p_member_id bigint
) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_me bigint := fn_my_user_id();
    v_m home_member%rowtype;
    v_kind text;
    v_code text;
    v_id bigint;
begin
    if v_me is null then
        raise exception 'Not Allowed' using errcode = '42501';
    end if;
    if p_home_id is null then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    if p_kind is not null and p_kind not in ('adult', 'child', 'relative', 'guest') then
        raise exception 'Invalid member' using errcode = 'P0001';   -- pet o fuera del enum
    end if;
    if p_kind is null and p_member_id is null then
        raise exception 'Invalid member' using errcode = 'P0001';
    end if;
    perform fn_home_mutation_guard(p_home_id);
    perform fn_require_permission(p_home_id, 'home.invite');
    if p_member_id is not null then
        -- Inexistente y de otro hogar dan el mismo error (sin oráculo de ids).
        select * into v_m from home_member hm where hm.id = p_member_id for update;
        if not found or v_m.home_id <> p_home_id or v_m.kind = 'pet' or v_m.status <> 'active'
           or v_m.app_user_id is not null or (p_kind is not null and p_kind <> v_m.kind::text) then
            raise exception 'Invalid member' using errcode = 'P0001';
        end if;
        v_kind := v_m.kind::text;
    else
        v_kind := p_kind;
    end if;
    if v_kind = 'adult' and not fn_is_home_admin(p_home_id) then
        raise exception 'Not Allowed' using errcode = '42501';      -- D-017
    end if;
    v_code := encode(extensions.gen_random_bytes(16), 'hex');
    insert into home_invitation (home_id, kind, member_id, code_hash, status, expires_at, created_by)
    values (p_home_id, v_kind::member_kind, p_member_id,
            encode(sha256(convert_to(v_code, 'UTF8')), 'hex'), 'pending',
            (now() at time zone 'UTC') + interval '7 days', v_me)
    returning id into v_id;
    insert into audit_log (home_id, actor_app_user_id, action, target_type, target_id, payload)
    values (p_home_id, v_me, 'home.invitation.create', 'home_invitation', v_id,
            jsonb_build_object('invitation_id', v_id, 'kind', v_kind, 'member_id', p_member_id));
    return (fn_home_invitation_json(v_id)::jsonb || jsonb_build_object('code', v_code))::json;
end $$;

-- POST /home/invitation/accept {code}: código nulo, mal formado, inexistente, usado, revocado o
-- caducado, u hogar archived → el mismo 'Not Found' (sin oráculo); membresía existente →
-- 'Already member' sin consumir; miembro objetivo ya no válido → 'Invalid member' sin consumir.
-- Membresía antes de fijar app_user_id (FK compuesta home_member_membership_fk, 0012).
create or replace function accept_home_invitation(p_code text) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_me bigint := fn_my_user_id();
    v_now timestamp without time zone := (now() at time zone 'UTC');
    v_code text;
    v_hash text;
    v_home bigint;
    v_status home_status;
    v_inv home_invitation%rowtype;
    v_m home_member%rowtype;
    v_kind member_kind;
    v_mid bigint;
    v_hm bigint;
    v_name text;
    v_color text;
    v_n integer;
begin
    if v_me is null then
        raise exception 'Not Allowed' using errcode = '42501';
    end if;
    v_code := lower(btrim(coalesce(p_code, ''), E' \t\r\n'));   -- espacios y saltos de línea
    if v_code !~ '^[0-9a-f]{32}$' then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    v_hash := encode(sha256(convert_to(v_code, 'UTF8')), 'hex');
    -- Lectura previa sin lock: solo decide qué hogar bloquear.
    select i.home_id into v_home from home_invitation i where i.code_hash = v_hash;
    if not found then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    select h.status into v_status from home h where h.id = v_home for update;
    if not found or v_status = 'archived' then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    -- Relectura bajo el lock de hogar (paso 1 del diseño): pendiente y no caducada.
    select * into v_inv from home_invitation i
     where i.code_hash = v_hash and i.home_id = v_home
       and i.status = 'pending' and i.expires_at > v_now;
    if not found then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    if exists (select 1 from home_membership hm
               where hm.home_id = v_home and hm.app_user_id = v_me) then
        raise exception 'Already member' using errcode = 'P0001';   -- no consume (paso 2)
    end if;
    if v_inv.member_id is not null then
        select * into v_m from home_member hm where hm.id = v_inv.member_id for update;
        if not found or v_m.home_id <> v_home or v_m.kind = 'pet' or v_m.status <> 'active'
           or v_m.app_user_id is not null then
            raise exception 'Invalid member' using errcode = 'P0001';
        end if;
        if v_m.kind = 'adult' and v_inv.kind <> 'adult' then
            raise exception 'Invalid member' using errcode = 'P0001';   -- D-017
        end if;
        v_kind := v_m.kind;
    else
        v_kind := v_inv.kind;
    end if;
    insert into home_membership (home_id, app_user_id, role)
    values (v_home, v_me, 'member') returning id into v_mid;
    if v_inv.member_id is not null then
        update home_member set app_user_id = v_me, updated_at = v_now where id = v_inv.member_id;
        v_hm := v_inv.member_id;
    else
        select f.v_name, f.v_color into v_name, v_color
          from app_user u, fn_validate_person_fields(u.name, '#6923E2') f where u.id = v_me;
        insert into home_member (home_id, kind, name, color, status, app_user_id, created_by)
        values (v_home, v_kind, v_name, v_color, 'active', v_me, v_me) returning id into v_hm;
        insert into person (user_id, home_id, home_member_id, name, color)
        values (v_me, v_home, v_hm, v_name, v_color);
    end if;
    perform fn_seed_kind_permissions(v_mid, v_kind);
    perform 1 from home_invitation i where i.id = v_inv.id for update;
    update home_invitation
       set status = 'accepted', accepted_by = v_me, accepted_at = v_now, updated_at = v_now
     where id = v_inv.id and status = 'pending';
    get diagnostics v_n = row_count;
    if v_n = 0 then
        raise exception 'Not Found' using errcode = 'P0002';   -- deshace membresía y snapshot
    end if;
    insert into audit_log (home_id, actor_app_user_id, action, target_type, target_id, payload)
    values (v_home, v_me, 'home.invitation.accept', 'home_invitation', v_inv.id,
            jsonb_build_object('invitation_id', v_inv.id, 'membership_id', v_mid,
                               'member_id', v_hm, 'kind', v_kind::text));
    return json_build_object('home_id', v_home, 'membership_id', v_mid, 'member_id', v_hm,
                             'role', 'member', 'kind', v_kind::text);
end $$;

-- POST /home/invitation/revoke {home_id, id}: pending no caducada → revoked; otro hogar, otro
-- estado o caducada → Not Found.
create or replace function revoke_home_invitation(p_home_id bigint, p_id bigint) returns json
language plpgsql security definer set search_path = public as $$
declare
    v_me bigint := fn_my_user_id();
    v_inv home_invitation%rowtype;
begin
    if v_me is null then
        raise exception 'Not Allowed' using errcode = '42501';
    end if;
    if p_home_id is null or p_id is null then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    perform fn_home_mutation_guard(p_home_id);
    perform fn_require_permission(p_home_id, 'home.invite');
    select * into v_inv from home_invitation i
     where i.id = p_id and i.home_id = p_home_id for update;
    if not found or v_inv.status <> 'pending' or v_inv.expires_at <= (now() at time zone 'UTC') then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
    update home_invitation set status = 'revoked', updated_at = (now() at time zone 'UTC')
     where id = p_id;
    insert into audit_log (home_id, actor_app_user_id, action, target_type, target_id, payload)
    values (p_home_id, v_me, 'home.invitation.revoke', 'home_invitation', p_id,
            jsonb_build_object('invitation_id', p_id, 'kind', v_inv.kind::text,
                               'member_id', v_inv.member_id));
    return fn_home_invitation_json(p_id);
end $$;

