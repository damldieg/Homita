-- 0012_home_schema.sql — Modelo de datos de Home y membresías (fase 1.3, tarjeta 1.3; spec 1.1 §5).
-- DDL aditivo del diseño aprobado (diseno-home.md r3, D-010): enums, tablas nuevas, columnas
-- nullables en tablas existentes, índices, RLS deny-by-default, seed de catálogo y helpers.
--
-- Notas:
-- * Desviación D-a (arrastre 1.1 R1-01): en helpers, 'Not Found' usa errcode 'P0002' y
--   'Not Allowed' usa errcode '42501' (convención de 0005/0006/0008/0011 y HTTP 403 en PostgREST
--   directo). 'Invalid home' y 'Home header required' siguen en 'P0001' (el Edge mapea por texto
--   en RPC_STATUS).
-- * Desviación D-b (arrastre 1.1 R1-02): revoke all sobre todas las secuencias de public a
--   anon/authenticated (defensa en profundidad sobre secuencias IDENTITY).
-- * NO crea home_member_permission ni home_invitation (van en 0022, tarjeta 1.15).
-- * Sin NOT NULL ni UNIQUE sobre columnas nuevas de tablas existentes (eso va en 0015, §6.H).
-- * Constraints de unicidad/FK compuestas y trigger anti-hogar-sin-admin: 0015 (§6.H, 1.1).

-- ─────────────────────────────── A. Tipos ───────────────────────────────

create type home_role as enum ('admin', 'member');
create type member_kind as enum ('adult', 'child', 'relative', 'guest', 'pet');
create type home_status as enum ('active', 'archived');
create type member_status as enum ('active', 'inactive');

-- ─────────────────────────────── B. Tablas nuevas ───────────────────────────────

create table home (
    id bigint generated by default as identity primary key,
    name text not null check (btrim(name) <> ''),
    timezone text not null default 'Europe/Madrid',
    status home_status not null default 'active',
    is_personal boolean not null default false,
    created_by bigint references app_user (id) on delete set null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC')
);

create table home_membership (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id),
    app_user_id bigint not null references app_user (id) on delete cascade,
    role home_role not null default 'member',
    joined_at timestamp without time zone not null default (now() at time zone 'UTC'),
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    constraint home_membership_home_user_key unique (home_id, app_user_id),
    constraint home_membership_id_home_key unique (id, home_id)
);
create index home_membership_app_user_idx on home_membership (app_user_id);

create table home_member (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id),
    kind member_kind not null,
    name text not null check (btrim(name) <> ''),
    color text not null default '#6923E2',
    app_user_id bigint,
    status member_status not null default 'active',
    created_by bigint references app_user (id) on delete set null,
    created_at timestamp without time zone not null default (now() at time zone 'UTC'),
    updated_at timestamp without time zone not null default (now() at time zone 'UTC'),
    constraint home_member_id_home_key unique (id, home_id),
    constraint home_member_pet_without_account check (kind <> 'pet' or app_user_id is null),
    constraint home_member_membership_fk foreign key (home_id, app_user_id)
        references home_membership (home_id, app_user_id) on delete set null (app_user_id)
);
create unique index home_member_linked_key on home_member (home_id, app_user_id)
    where app_user_id is not null;
create index home_member_home_idx on home_member (home_id);

create table permission (
    code text primary key,
    domain text not null,
    description text not null
);

create table member_kind_default (
    kind member_kind not null,
    permission_code text not null references permission (code),
    primary key (kind, permission_code),
    constraint member_kind_default_no_pet check (kind <> 'pet')
);

create table membership_permission (
    home_membership_id bigint not null references home_membership (id) on delete cascade,
    permission_code text not null references permission (code),
    primary key (home_membership_id, permission_code)
);

create table audit_log (
    id bigint generated by default as identity primary key,
    home_id bigint not null references home (id),
    actor_app_user_id bigint references app_user (id) on delete set null,
    action text not null check (btrim(action) <> ''),
    target_type text not null,
    target_id bigint,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamp without time zone not null default (now() at time zone 'UTC')
);
create index audit_log_home_created_idx on audit_log (home_id, created_at);

