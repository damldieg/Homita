-- ─────────────────────────────── G. Helpers SECURITY DEFINER (§3.4) ───────────────────────────────
-- Orden de creación: las funciones SQL validan cuerpo al crearse.

create or replace function fn_active_home_id() returns bigint
language plpgsql stable security definer set search_path = public as $$
declare
    v_raw text := nullif((nullif(current_setting('request.headers', true), '')::json) ->> 'x-home-id', '');
begin
    if v_raw is null then
        return null;
    end if;
    if v_raw !~ '^[0-9]{1,18}$' then
        raise exception 'Invalid home' using errcode = 'P0001';
    end if;
    return v_raw::bigint;
end $$;

create or replace function fn_my_home_ids() returns bigint[]
language sql stable security definer set search_path = public as $$
    select coalesce(array_agg(home_id), array[]::bigint[])
    from home_membership where app_user_id = fn_my_user_id()
$$;

create or replace function fn_home_role(p_home_id bigint) returns home_role
language sql stable security definer set search_path = public as $$
    select hm.role from home_membership hm
    where hm.home_id = p_home_id and hm.app_user_id = fn_my_user_id()
$$;

create or replace function fn_is_home_admin(p_home_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select coalesce(fn_home_role(p_home_id) = 'admin', false)
$$;

create or replace function fn_has_permission(p_home_id bigint, p_code text) returns boolean
language sql stable security definer set search_path = public as $$
    select exists (
        select 1 from home_membership hm
        where hm.home_id = p_home_id
          and hm.app_user_id = fn_my_user_id()
          and (hm.role = 'admin'
               or exists (select 1 from membership_permission mp
                          where mp.home_membership_id = hm.id
                            and mp.permission_code = p_code))
    )
$$;

-- D-a: 'Not Found' → P0002 (antes P0001 en la spec 1.1).
create or replace function fn_require_member(p_home_id bigint) returns void
language plpgsql stable security definer set search_path = public as $$
begin
    if p_home_id is null or not (p_home_id = any (fn_my_home_ids())) then
        raise exception 'Not Found' using errcode = 'P0002';
    end if;
end $$;

-- D-a: 'Not Allowed' → 42501 (antes P0001 en la spec 1.1).
create or replace function fn_require_permission(p_home_id bigint, p_code text) returns void
language plpgsql stable security definer set search_path = public as $$
begin
    perform fn_require_member(p_home_id);
    if not fn_has_permission(p_home_id, p_code) then
        raise exception 'Not Allowed' using errcode = '42501';
    end if;
end $$;

create or replace function fn_home_for_root_create() returns bigint
language plpgsql stable security definer set search_path = public as $$
declare
    v_active bigint := fn_active_home_id();
    v_default bigint;
    v_count integer;
    v_only bigint;
begin
    if v_active is not null then
        perform fn_require_member(v_active);
        return v_active;
    end if;
    select au.default_home_id into v_default from app_user au where au.id = fn_my_user_id();
    if v_default is not null and v_default = any (fn_my_home_ids()) then
        return v_default;
    end if;
    select count(*), min(home_id) into v_count, v_only
    from home_membership where app_user_id = fn_my_user_id();
    if v_count = 1 then
        return v_only;
    end if;
    raise exception 'Home header required' using errcode = 'P0001';
end $$;

create or replace function fn_home_of_calendar(p_calendar_id bigint) returns bigint
language sql stable security definer set search_path = public as $$
    select home_id from calendar where id = p_calendar_id
$$;

create or replace function fn_home_of_task_list(p_task_list_id bigint) returns bigint
language sql stable security definer set search_path = public as $$
    select home_id from task_list where id = p_task_list_id
$$;

create or replace function fn_home_of_person(p_person_id bigint) returns bigint
language sql stable security definer set search_path = public as $$
    select home_id from person where id = p_person_id
$$;

-- Grants (A5, A6): fn_home_of_* y fn_require_* NO a authenticated (oráculo id→hogar);
-- solo las llaman RPC SECURITY DEFINER (owner) y 0014/0020.
revoke execute on function fn_active_home_id(), fn_my_home_ids(), fn_home_role(bigint),
    fn_is_home_admin(bigint), fn_has_permission(bigint, text), fn_require_member(bigint),
    fn_require_permission(bigint, text), fn_home_for_root_create(),
    fn_home_of_calendar(bigint), fn_home_of_task_list(bigint), fn_home_of_person(bigint)
    from public, anon;

